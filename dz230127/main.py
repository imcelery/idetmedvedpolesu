# Поиск в глубину (англ. Depth-first search, DFS) — один из методов обхода графа. Стратегия поиска в глубину, как и следует из названия, состоит в том, чтобы идти «вглубь» графа, насколько это возможно
# Алгоритм поиска описывается рекурсивно: перебираем все исходящие из рассматриваемой вершины рёбра
# Если ребро ведёт в вершину, которая не была рассмотрена ранее, то запускаем алгоритм от этой нерассмотренной вершины, а после возвращаемся и продолжаем перебирать рёбр

#рекурсия
def bo(al: Dict[str, List[str]], s: deque, fin: str, alreafyposidely: []):
    #если мы в нужной вершине выходим
    if s[len(s) - 1] == fin:
        return s
    # елси нет то продолжаем рекурсию из текущей вершины
    n = al[s[len(s) - 1]]
    # проходим по всем доступным вершинам
    for i in n:
        #если мы тут еще небыли
        if i not in alreafyposidely:
            ns = s.copy()
            ns.append(i)
            alreafyposidely.append(i)
            # запускаем рекурсию от новой вершины
            a = bo(al, ns, fin, alreafyposidely)
            # если вернулась очередь значит мы нашли путь
            if type(a) == deque:
                return a
            else:
                alreafyposidely.extend(a)
    return alreafyposidely
    #возращаем очередь если нашли путь а если нет возращем список пройденных вершин


def dfs(al: Dict[str, List[str]], start: str, finish: str) -> List[str]:
    s = deque()
    s.append(start)
    #вызываем рекурсию
    a = bo(al, s, finish, [start])
    #если вернулась очередь то ответ есть
    if type(a) == deque:
        return list(a)
    else:
        return "нет такого"



# Поиск в ширину (англ. breadth-first search, BFS) — тоже один из методов обхода графа (прикол да)
# Алгоритм заключается в постепенном равномерном наращиваннии дерева вариантов.

def bfs(al: Dict[str, List[str]], start: str, finish: str) -> List[str]:

    #очередь из которой все вызывается
    o = deque()
    #обавляем в неё начальную вершину
    o.append(start)
    #словарь путей ко всем пройденным вершинам чтобы восстановить обратный путь
    puti = {}
    #чтобы знать когда из цикла выходить
    f = False

    #проверяем, есть ли откуда расти
    while len(o) != 0:
        a = o.popleft()
        #отращиваем новую ветвь из точки а
        for i in al[a]:
            # проверяем были ли мы уже тут
            if i not in puti.keys():
                o.append(i)
                puti.update({i : a})
                #проверка на финиш
                if i == finish:
                    #готча (ну типа попался, типа покемоны ну вы поняли)
                    f = True
                    break


        if(f):
            break

    #если нашли
    if f:
        o = [finish]
        #по словарю путей находим обратный путь из финиша к старту
        n = finish
        while True:
            n = puti[n]
            o.append(n)
            if n == start:
                break
        #азворачиваем и выводим
        return list(reversed(o))
    else:
        return 'нет такого'



