def f(n):
    #нициализируем массив каждого положения
    #ервое число - колво способов с другим животным сзади
    # вь=торое, третье с 1  акими же животными сзади


    a = [[0, 0, 0] for _ in range(n + 1)]
    #попасть на первый можно одним способом
    a[0][0] = 1



    #обновляем для следующих элементов
    for i in range(len(a) - 2):
        a[i + 1][0] += sum(a[i])
        a[i + 1][1] += a[i][0]



    return sum(a[n - 1]) * 2

