def f(n):
    #нициализируем массив каждого положения
    a = [0 for _ in range(n + 1)]
    #попасть на первый можно одним способом
    a[0] = 1

    #обновляем для следующих элементов
    for i in range(len(a) - 2):
        a[i + 1] += a[i]
        a[i + 2] += a[i]

    return a[n-1]

if __name__ == "__main__":
    n = int(input())
    print(f(n))