def f(n):
    #нициализируем массив каждого положения
    #ервое число - колво способов с некрутыми отходами в данной клетке
    # торое-  с крутыми но сзади некрутые
    # третье - с крутыми и сзади крутые
    a = [[0, 0, 0] for _ in range(n)]
    #попасть на первый можно одним способом
    a[0][0] = 1
    a[0][1] = 1

    #обновляем для следующих элементов
    for i in range(len(a) - 1):

        a[i + 1][0] += sum(a[i])
        a[i + 1][1] +=  a[i][0]
        a[i + 1][2] += a[i][1]


    return sum(a[n-1])

